// 1. Что такое указатель?
//    - Указатель - это переменная, которая хранит АДРЕС другой переменной
//    - Объявление: тип* имя = &переменная;
//    - int* p = &x;  // p хранит адрес x
//
// 2. Операторы:
//    - & (амперсанд) - оператор взятия адреса
//    - * (звёздочка) - оператор разыменования (получение значения по адресу)
//
// 3. Пример:
//    int x = 42;
//    int* p = &x;     // p хранит адрес x
//    cout << *p;      // разыменование → 42
//    *p = 100;        // меняем x через указатель
//
// 4. Арифметика указателей:
//    - p++  → сдвиг на sizeof(тип) байт
//    - p+2  → сдвиг на 2 элемента
//    - p1 - p2 → количество элементов между адресами
//
// 5. Указатели и массивы:
//    - Имя массива = указатель на первый элемент
//    - int arr[] = {1,2,3};  // arr == &arr[0]
//    - arr[i] == *(arr + i)
//
// 6. Передача в функции:
//    - По указателю (меняем оригинал): void func(int* p)
//    - Массив передаётся как указатель: void func(int* arr, int size)
//
// 7. nullptr:
//    - Указатель, который никуда не указывает
//    - int* p = nullptr;
//    - Всегда проверяйте: if(p) { /* безопасно */ }
//
// 8. Указатель на указатель:
//    - int** pp = &p;  // указатель на указатель
//    - **pp = 100;     // меняем исходную переменную
//
// 9. const и указатели:
//    - const int* p → нельзя менять *p (данные)
//    - int* const p → нельзя менять p (адрес)
//    - const int* const p → нельзя менять ни то, ни другое
//
// 10. C-строки:
//     - const char* str = "Hello";
//     - Указатель на первый символ строки
//     - Проход по строке: while(*str) { ... str++; }
// ============================================================

#include <iostream>
using namespace std;

// ========== 1. АДРЕС И РАЗЫМЕНОВАНИЕ ==========
void demo_address_dereference() {
    cout << "\n=== 1. Адрес и разыменование ===\n";
    
    int x = 42;
    int* p = &x;     // p хранит адрес x
    
    cout << "Значение x: " << x << endl;
    cout << "Адрес x: " << &x << endl;
    cout << "Значение p (адрес): " << p << endl;
    cout << "Разыменование *p: " << *p << endl; // разыменование → 42
    
    *p = 100;        // меняем x через указатель
    cout << "x после *p = 100: " << x << endl;
}

// ========== 2. АРИФМЕТИКА УКАЗАТЕЛЕЙ ==========
void demo_pointer_arithmetic() {
    cout << "\n=== 2. Арифметика указателей ===\n";
    
    int arr[] = {10, 20, 30, 40, 50};
    int* p = arr;    // указывает на arr[0]
    
    cout << "Массив: ";
    for(int i = 0; i < 5; i++) 
        cout << arr[i] << " ";
    cout << endl;
    
    cout << "*p = " << *p << " (arr[0])" << endl;
    p++;             // сдвиг на sizeof(int) байт
    cout << "p++ -> *p = " << *p << " (arr[1])" << endl;
    p += 2;          // сдвиг на 2 элемента
    cout << "p += 2 -> *p = " << *p << " (arr[3])" << endl;
    p--;             // назад на 1
    cout << "p-- -> *p = " << *p << " (arr[2])" << endl;
    
    // Индексация работает как с массивом
    cout << "p[1] = " << p[1] << " (arr[3])" << endl;
    
    // Разность указателей
    int* start = arr;
    int* end = arr + 5;
    cout << "Количество элементов: " << (end - start) << endl;
}

// ========== 3. ПЕРЕДАЧА В ФУНКЦИИ ==========
// Передача по указателю (изменяем оригинал)
void swap(int* a, int* b) {
    int tmp = *a;
    *a = *b;
    *b = tmp;
}

// Передача массива (деградирует в указатель)
void print_array(int* arr, int size) {
    cout << "Массив: ";
    for(int i = 0; i < size; i++)
        cout << arr[i] << " ";
    cout << endl;
}

void demo_function_pointers() {
    cout << "\n=== 3. Передача указателей в функции ===\n";
    
    int a = 5, b = 10;
    cout << "До swap: a=" << a << ", b=" << b << endl;
    swap(&a, &b);
    cout << "После swap: a=" << a << ", b=" << b << endl;
    
    int arr[] = {1, 2, 3, 4, 5};
    print_array(arr, 5);  // массив деградирует в указатель
}

// ========== 4. NULLPTR И ПРОВЕРКА ==========
void demo_nullptr() {
    cout << "\n=== 4. nullptr и проверка ===\n";
    
    int* p1 = nullptr;
    int x = 42;
    int* p2 = &x;
    
    cout << "p1 = " << (p1 ? "не null" : "nullptr") << endl;
    cout << "p2 = " << (p2 ? "не null" : "nullptr") << endl;
    
    // Безопасное разыменование
    if(p2) {
        cout << "*p2 = " << *p2 << endl;
    }
    
    // Динамическая память
    int* p3 = new int(100);
    cout << "*p3 = " << *p3 << endl;
    delete p3;
    p3 = nullptr;  // хорошая практика - обнулять после delete
    cout << "p3 после delete: " << (p3 ? "не null" : "nullptr") << endl;
}

// ========== 5. УКАЗАТЕЛЬ НА УКАЗАТЕЛЬ ==========
void demo_pointer_to_pointer() {
    cout << "\n=== 5. Указатель на указатель ===\n";
    
    int x = 5;
    int* p = &x;
    int** pp = &p;   // указатель на указатель
    
    cout << "x = " << x << endl;
    cout << "p = " << p << " (адрес x)" << endl;
    cout << "*p = " << *p << endl;
    cout << "pp = " << pp << " (адрес p)" << endl;
    cout << "*pp = " << *pp << " (значение p = адрес x)" << endl;
    cout << "**pp = " << **pp << " (значение x)" << endl;
    
    **pp = 100;  // меняем x через двойной указатель
    cout << "x после **pp = 100: " << x << endl;
}

// ========== 6. CONST И УКАЗАТЕЛИ ==========
void demo_const_pointers() {
    cout << "\n=== 6. const и указатели ===\n";
    
    int x = 10, y = 20;
    
    // 1. Указатель на константные данные (нельзя менять *p)
    const int* p1 = &x;
    cout << "*p1 = " << *p1 << " (нельзя изменить)" << endl;
    // *p1 = 15;  // ОШИБКА!
    p1 = &y;      // можно перенаправить
    cout << "p1 перенаправлен на y: *p1 = " << *p1 << endl;
    
    // 2. Константный указатель (нельзя менять адрес)
    int* const p2 = &x;
    *p2 = 15;     // можно изменить данные
    cout << "*p2 = " << *p2 << " (данные изменены)" << endl;
    // p2 = &y;   // ОШИБКА!
    
    // 3. Константный указатель на константные данные
    const int* const p3 = &x;
    // *p3 = 30;  // ОШИБКА!
    // p3 = &y;   // ОШИБКА!
    cout << "*p3 = " << *p3 << " (ничего нельзя изменить)" << endl;
}

// ========== 7. ДОПОЛНИТЕЛЬНО: УКАЗАТЕЛИ И СТРОКИ ==========
void demo_string_pointers() {
    cout << "\n=== 7. Указатели и C-строки ===\n";
    
    const char* str = "Hello, World!";
    cout << "Строка: " << str << endl;
    cout << "Первый символ: " << *str << endl;
    cout << "Третий символ: " << *(str + 2) << endl;
    
    // Проход по строке
    const char* p = str;
    cout << "Символы: ";
    while(*p) {
        cout << *p << " ";
        p++;
    }
    cout << endl;
}

