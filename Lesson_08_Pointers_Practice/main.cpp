int main() {
    cout << "========== ПРАКТИКА ПО УКАЗАТЕЛЯМ ==========\n";
    
    demo_address_dereference();
    demo_pointer_arithmetic();
    demo_function_pointers();
    demo_nullptr();
    demo_pointer_to_pointer();
    demo_const_pointers();
    demo_string_pointers();
    
    return 0;
}