
/*

Динамическая структура данных, где элементы (узлы) связаны через указатели.
Не хранятся в памяти подряд, в отличие от массивов.
/*
 * ================================================================
 *          КРАТКИЙ СПРАВОЧНИК ПО ОПЕРАЦИЯМ std::list
 * ================================================================
 *
 * СОЗДАНИЕ
 * ----------------------------------------------------------------
 *   Пустой список                   →  list<int> l;
 *   С элементами                    →  list<int> l = {1, 2, 3, 4, 5};
 *   N копий значения                →  list<int> l(5, 100);
 *   Копирование                     →  list<int> l2(l1);
 *   Перемещение                     →  list<int> l2(std::move(l1));
 *   Из массива                      →  list<int> l(std::begin(arr), std::end(arr));
 *
 * ДОБАВЛЕНИЕ
 * ----------------------------------------------------------------
 *   В начало                        →  l.push_front(10);        [O(1)]
 *   В конец                         →  l.push_back(20);         [O(1)]
 *   Перед итератором                →  l.insert(it, 30);        [O(1)]
 *   После итератора                 →  l.insert(std::next(it), 40); [O(1)]
 *   Несколько элементов             →  l.insert(it, 3, 50);     [O(1)]
 *
 * УДАЛЕНИЕ
 * ----------------------------------------------------------------
 *   Из начала                       →  l.pop_front();           [O(1)]
 *   Из конца                        →  l.pop_back();            [O(1)]
 *   По значению (все вхождения)     →  l.remove(10);            [O(n)]
 *   По условию (лямбда)             →  l.remove_if([](int x) { return x % 2 == 0; }); [O(n)]
 *   По итератору                    →  l.erase(it);             [O(1)]
 *   Диапазон                        →  l.erase(it1, it2);       [O(n)]
 *   Очистить всё                    →  l.clear();               [O(n)]
 *
 * ДОСТУП
 * ----------------------------------------------------------------
 *   Первый элемент                  →  l.front();               [O(1)]
 *   Последний элемент               →  l.back();                [O(1)]
 *   По индексу (через итератор)     →  *std::next(l.begin(), i); [O(n)]
 *
 * ПОИСК И ПРОВЕРКИ
 * ----------------------------------------------------------------
 *   По значению                     →  std::find(l.begin(), l.end(), x); [O(n)]
 *   По условию                      →  std::find_if(l.begin(), l.end(), [](int x) { return x > 10; }); [O(n)]
 *   Проверка наличия                →  std::find(...) != l.end(); [O(n)]
 *   Размер                          →  l.size();                [O(1)]
 *   Пуст?                           →  l.empty();               [O(1)]
 *   Макс. размер                    →  l.max_size();            [O(1)]
 *
 * ПРЕОБРАЗОВАНИЕ
 * ----------------------------------------------------------------
 *   Сортировка                      →  l.sort();                [O(n log n)]
 *   Разворот                        →  l.reverse();             [O(n)]
 *   Удаление дубликатов (сортир.)   →  l.unique();              [O(n)]
 *   Слияние (оба сортированы)       →  l1.merge(l2);            [O(n)]
 *   Перемещение всех (splice)       →  l1.splice(it, l2);       [O(1)]
 *   Перемещение одного (splice)     →  l1.splice(it, l2, it2);  [O(1)]
 *
 * ОБХОД
 * ----------------------------------------------------------------
 *   Вперёд (range-based for)        →  for (int x : l) { ... }  [O(n)]
 *   Вперёд (итераторы)              →  for (auto it = l.begin(); it != l.end(); ++it) { ... } [O(n)]
 *   Назад (обратные итераторы)      →  for (auto it = l.rbegin(); it != l.rend(); ++it) { ... } [O(n)]
 *
 * АЛГОРИТМЫ ИЗ <algorithm>
 * ----------------------------------------------------------------
 *   Минимальный элемент             →  *std::min_element(l.begin(), l.end()); [O(n)]
 *   Максимальный элемент            →  *std::max_element(l.begin(), l.end()); [O(n)]
 *   Замена значений                 →  std::replace(l.begin(), l.end(), old, new); [O(n)]
 *   Копирование в другой контейнер  →  std::copy(l.begin(), l.end(), std::back_inserter(vec)); [O(n)]
 *
 * ВАЖНЫЕ ОСОБЕННОСТИ
 * ----------------------------------------------------------------
 *   - Двусвязный список (каждый элемент знает предыдущий и следующий)
 *   - Нет оператора [] (доступ по индексу - O(n))
 *   - Вставка/удаление в середине - O(1) (если есть итератор)
 *   - Не инвалидирует итераторы при вставке/удалении (кроме удалённого)
 *   - Для sort() использует свой метод, т.к. std::sort требует произвольного доступа
 *   - unique() работает ТОЛЬКО на отсортированном списке
 *   - merge() требует, чтобы оба списка были отсортированы
 * ================================================================
 */



#include <iostream>     // Для cout, cin
#include <list>         // Для std::list
#include <algorithm>    // Для find, find_if, replace, min_element, max_element
#include <numeric>      // Для accumulate (сумма)
#include <string>       // Для std::string

using namespace std;

int main() {
    // ============================================================
    // 1. СПОСОБЫ СОЗДАНИЯ СПИСКА
    // ============================================================
    cout << "========== 1. СОЗДАНИЕ СПИСКА ==========\n";
    
    // Пустой список
    list<int> emptyList;
    cout << "Пустой список, размер: " << emptyList.size() << "\n";
    
    // Список с элементами через initializer_list (фигурные скобки)
    list<int> list1 = {10, 20, 30, 40, 50};
    cout << "list1: ";
    for (int x : list1) cout << x << " ";
    cout << "\n";
    
    // Список из 5 элементов, каждый равен 100
    list<int> list2(5, 100);  // 5 раз по 100
    cout << "list2 (5 раз по 100): ";
    for (int x : list2) cout << x << " ";
    cout << "\n";
    
    // Копирование списка (конструктор копирования)
    list<int> list3 = list1;  // Создаём копию list1
    cout << "list3 (копия list1): ";
    for (int x : list3) cout << x << " ";
    cout << "\n";
    
    // Перемещение списка (конструктор перемещения)
    list<int> list4 = move(list3);  // list3 становится пустым
    cout << "list4 (перемещен из list3): ";
    for (int x : list4) cout << x << " ";
    cout << "\n";
    cout << "list3 после перемещения (пустой): " << list3.size() << "\n";
    
    // Создание списка из массива
    int arr[] = {1, 2, 3, 4, 5};
    list<int> list5(begin(arr), end(arr));  // Из массива в список
    cout << "list5 (из массива): ";
    for (int x : list5) cout << x << " ";
    cout << "\n";
    
    
    // ============================================================
    // 2. ДОБАВЛЕНИЕ ЭЛЕМЕНТОВ
    // ============================================================
    cout << "\n========== 2. ДОБАВЛЕНИЕ ЭЛЕМЕНТОВ ==========\n";
    list<int> myList = {10, 20, 30};
    
    // Вставка в начало (O(1))
    myList.push_front(5);
    // Вставка в конец (O(1))
    myList.push_back(40);
    cout << "После push_front(5) и push_back(40): ";
    for (int x : myList) cout << x << " ";  // 5 10 20 30 40
    cout << "\n";
    
    // Вставка перед указанным элементом (O(1))
    auto it = find(myList.begin(), myList.end(), 20);  // Находим 20
    if (it != myList.end()) {
        myList.insert(it, 99);  // Вставляем 99 перед 20
        cout << "После insert перед 20: ";
        for (int x : myList) cout << x << " ";  // 5 10 99 20 30 40
        cout << "\n";
    }
    
    // Вставка после указанного элемента (O(1))
    auto it2 = find(myList.begin(), myList.end(), 30);  // Находим 30
    if (it2 != myList.end()) {
        myList.insert(next(it2), 777);  // Вставляем после 30
        cout << "После insert после 30: ";
        for (int x : myList) cout << x << " ";  // 5 10 99 20 30 777 40
        cout << "\n";
    }
    
    // Вставка нескольких одинаковых элементов (O(1))
    myList.insert(myList.begin(), 3, 888);  // 3 раза по 888 в начало
    cout << "После вставки 3 раз 888 в начало: ";
    for (int x : myList) cout << x << " ";  // 888 888 888 5 10 99 20 30 777 40
    cout << "\n";
    
    
    // ============================================================
    // 3. УДАЛЕНИЕ ЭЛЕМЕНТОВ
    // ============================================================
    cout << "\n========== 3. УДАЛЕНИЕ ЭЛЕМЕНТОВ ==========\n";
    
    // Удаление из начала (O(1))
    myList.pop_front();
    // Удаление из конца (O(1))
    myList.pop_back();
    cout << "После pop_front() и pop_back(): ";
    for (int x : myList) cout << x << " ";
    cout << "\n";
    
    // Добавляем элементы для демонстрации удаления
    myList.push_back(888);
    myList.push_back(888);
    cout << "Перед удалением 888: ";
    for (int x : myList) cout << x << " ";
    cout << "\n";
    
    // Удаление всех элементов с указанным значением (O(n))
    myList.remove(888);
    cout << "После remove(888): ";
    for (int x : myList) cout << x << " ";
    cout << "\n";
    
    // Удаление по условию (лямбда-функция) (O(n))
    myList.remove_if([](int x) { return x % 2 == 0; });  // Удаляем все чётные
    cout << "После remove_if (удалили все четные): ";
    for (int x : myList) cout << x << " ";
    cout << "\n";
    
    // Удаление по итератору (конкретный элемент) (O(1))
    auto toDelete = find(myList.begin(), myList.end(), 20);
    if (toDelete != myList.end()) {
        myList.erase(toDelete);  // Удаляем найденный элемент
        cout << "После erase(20): ";
        for (int x : myList) cout << x << " ";
        cout << "\n";
    }
    
    // Удаление диапазона элементов (O(n))
    auto first = find(myList.begin(), myList.end(), 30);   // Начало диапазона
    auto last = find(myList.begin(), myList.end(), 777);   // Конец диапазона
    if (first != myList.end() && last != myList.end()) {
        myList.erase(first, last);  // Удаляем от 30 до 777 (не включая 777)
        cout << "После erase(30, 777): ";
        for (int x : myList) cout << x << " ";
        cout << "\n";
    }
    
    // Полная очистка списка (O(n))
    myList.clear();
    cout << "После clear(), размер: " << myList.size() << "\n";
    
    
    // ============================================================
    // 4. ДОСТУП К ЭЛЕМЕНТАМ
    // ============================================================
    cout << "\n========== 4. ДОСТУП К ЭЛЕМЕНТАМ ==========\n";
    list<int> numberList = {100, 200, 300, 400, 500};
    
    // Доступ к первому элементу (O(1))
    cout << "Первый элемент: " << numberList.front() << "\n";   // 100
    
    // Доступ к последнему элементу (O(1))
    cout << "Последний элемент: " << numberList.back() << "\n"; // 500
    
    // Доступ по индексу через итератор (O(n))
    auto it3 = numberList.begin();      // Итератор на начало
    advance(it3, 2);                    // Перемещаем на 2 позиции вперёд
    cout << "Элемент по индексу 2: " << *it3 << "\n";  // 300
    
    // Альтернативный способ через next() (O(n))
    auto it4 = next(numberList.begin(), 3);  // Итератор на индекс 3
    cout << "Элемент по индексу 3: " << *it4 << "\n";  // 400
    
    
    // ============================================================
    // 5. ПОИСК И ПРОВЕРКИ
    // ============================================================
    cout << "\n========== 5. ПОИСК И ПРОВЕРКА ==========\n";
    numberList = {10, 20, 30, 40, 50};
    
    // Поиск элемента по значению (O(n))
    auto found = find(numberList.begin(), numberList.end(), 30);
    if (found != numberList.end()) {
        cout << "Найден элемент 30\n";
        cout << "Позиция: " << distance(numberList.begin(), found) << "\n";
    }
    
    // Проверка наличия элемента (O(n))
    bool has40 = find(numberList.begin(), numberList.end(), 40) != numberList.end();
    cout << "Содержит 40? " << (has40 ? "Да" : "Нет") << "\n";
    
    // Поиск по условию (первый элемент > 25) (O(n))
    auto found2 = find_if(numberList.begin(), numberList.end(), 
                          [](int x) { return x > 25; });
    if (found2 != numberList.end()) {
        cout << "Первый элемент > 25: " << *found2 << "\n";  // 30
    }
    
    // Размер списка (O(1) в C++11)
    cout << "Размер: " << numberList.size() << "\n";
    
    // Проверка на пустоту (O(1))
    cout << "Список пуст? " << (numberList.empty() ? "Да" : "Нет") << "\n";
    
    // Максимально возможный размер (O(1))
    cout << "Максимальный размер: " << numberList.max_size() << "\n";
    
    
    // ============================================================
    // 6. ПРЕОБРАЗОВАНИЕ И МОДИФИКАЦИЯ
    // ============================================================
    cout << "\n========== 6. ПРЕОБРАЗОВАНИЕ ==========\n";
    list<int> list7 = {1, 2, 3, 4, 5};
    list<int> list8 = {10, 20, 30};
    
    // Сортировка (O(n log n))
    list<int> unsorted = {5, 2, 8, 1, 9, 3};
    unsorted.sort();
    cout << "Отсортированный: ";
    for (int x : unsorted) cout << x << " ";  // 1 2 3 5 8 9
    cout << "\n";
    
    // Разворот списка (O(n))
    list7.reverse();
    cout << "Развернутый list7: ";
    for (int x : list7) cout << x << " ";  // 5 4 3 2 1
    cout << "\n";
    
    // Слияние двух ОТСОРТИРОВАННЫХ списков (O(n))
    list<int> sorted1 = {1, 3, 5, 7};
    list<int> sorted2 = {2, 4, 6, 8};
    sorted1.merge(sorted2);  // sorted2 становится пустым
    cout << "После слияния sorted1 и sorted2: ";
    for (int x : sorted1) cout << x << " ";  // 1 2 3 4 5 6 7 8
    cout << "\n";
    cout << "sorted2 после слияния (пустой): " << sorted2.size() << "\n";
    
    // Удаление дубликатов (ТОЛЬКО на ОТСОРТИРОВАННОМ списке) (O(n))
    list<int> duplicates = {1, 1, 2, 2, 3, 3, 3, 4};
    duplicates.sort();      // Сначала обязательно сортируем
    duplicates.unique();    // Удаляем повторяющиеся
    cout << "После unique: ";
    for (int x : duplicates) cout << x << " ";  // 1 2 3 4
    cout << "\n";
    
    // Перемещение элементов между списками (splice) (O(1))
    list<int> source = {100, 200, 300};
    list<int> target = {1, 2, 3};
    
    auto pos = next(target.begin(), 1);  // Позиция перед элементом 2
    target.splice(pos, source);  // Перемещаем ВСЕ элементы из source в target
    cout << "После splice: target = ";
    for (int x : target) cout << x << " ";  // 1 100 200 300 2 3
    cout << "\n";
    cout << "source после splice (пустой): " << source.size() << "\n";
    
    // Перемещение одного элемента (O(1))
    list<int> source2 = {10, 20, 30};
    list<int> target2 = {1, 2, 3};
    auto it5 = next(source2.begin());  // Итератор на элемент 20
    target2.splice(target2.end(), source2, it5);  // Перемещаем 20 в конец
    cout << "После перемещения 20: target2 = ";
    for (int x : target2) cout << x << " ";  // 1 2 3 20
    cout << "\n";
    cout << "source2: ";
    for (int x : source2) cout << x << " ";  // 10 30
    cout << "\n";
    
    
    // ============================================================
    // 7. ОБХОД И ИТЕРАТОРЫ
    // ============================================================
    cout << "\n========== 7. ОБХОД И ИТЕРАТОРЫ ==========\n";
    list<int> list9 = {10, 20, 30, 40, 50};
    
    // Обычный обход (range-based for, C++11)
    cout << "Range-based for: ";
    for (int x : list9) cout << x << " ";
    cout << "\n";
    
    // Обход через итераторы
    cout << "Итераторы: ";
    for (auto it6 = list9.begin(); it6 != list9.end(); ++it6) {
        cout << *it6 << " ";
    }
    cout << "\n";
    
    // Обратный обход (rbegin/rend)
    cout << "Обратный обход: ";
    for (auto it7 = list9.rbegin(); it7 != list9.rend(); ++it7) {
        cout << *it7 << " ";
    }
    cout << "\n";
    
    // Изменение элементов через ссылку
    for (auto& x : list9) {
        x *= 2;  // Удваиваем каждый элемент
    }
    cout << "После удвоения: ";
    for (int x : list9) cout << x << " ";  // 20 40 60 80 100
    cout << "\n";
    
    
    // ============================================================
    // 8. ПРИМЕНЕНИЕ АЛГОРИТМОВ ИЗ <algorithm>
    // ============================================================
    cout << "\n========== 8. ПРИМЕНЕНИЕ АЛГОРИТМОВ ==========\n";
    list<int> list10 = {5, 2, 8, 1, 9, 3, 7, 4, 6};
    
    // Сортировка (у list есть свой метод sort)
    list10.sort();
    cout << "Отсортированный: ";
    for (int x : list10) cout << x << " ";
    cout << "\n";
    
    // Сумма элементов (ручной подсчёт)
    int sum = 0;
    for (int x : list10) sum += x;
    cout << "Сумма: " << sum << "\n";
    
    // Минимальный элемент
    cout << "Мин: " << *min_element(list10.begin(), list10.end()) << "\n";
    
    // Максимальный элемент
    cout << "Макс: " << *max_element(list10.begin(), list10.end()) << "\n";
    
    // Замена всех значений (5 -> 99)
    replace(list10.begin(), list10.end(), 5, 99);
    cout << "После replace(5 -> 99): ";
    for (int x : list10) cout << x << " ";
    cout << "\n";
    
    
    // ============================================================
    // 9. ПРИМЕР РЕАЛЬНОГО ИСПОЛЬЗОВАНИЯ (список задач)
    // ============================================================
    cout << "\n========== 9. ПРИМЕР РЕАЛЬНОГО ИСПОЛЬЗОВАНИЯ ==========\n";
    // Список строк (задачи)
    list<string> tasks = {"Купить хлеб", "Сделать уроки", "Позвонить маме"};
    
    // Добавляем задачи в начало и конец
    tasks.push_front("Проснуться");
    tasks.push_back("Лечь спать");
    
    // Вставляем задачу в середину (перед "Сделать уроки")
    auto pos2 = find(tasks.begin(), tasks.end(), "Сделать уроки");
    if (pos2 != tasks.end()) {
        tasks.insert(pos2, "Пообедать");
    }
    
    // Удаляем выполненную задачу
    tasks.remove("Купить хлеб");
    
    // Выводим список задач с нумерацией
    int i = 1;
    cout << "Список задач:\n";
    for (const auto& task : tasks) {
        cout << i++ << ". " << task << "\n";
    }
    // Вывод:
    // 1. Проснуться
    // 2. Пообедать
    // 3. Сделать уроки
    // 4. Позвонить маме
    // 5. Лечь спать
    
    return 0;
}