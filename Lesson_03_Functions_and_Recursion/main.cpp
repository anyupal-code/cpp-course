// Вызов
//Структура: возвращаемый_тип имя(параметры) { тело }

//Рекурсия
//Рекурсия — вызов функции самой себя.
//Обязательно: условие выхода (базовый случай), иначе бесконечная рекурсия → переполнение стека.

// === ПРИМЕР КОДА ===
#include <iostream>
using namespace std;

// === ОБЫЧНЫЕ ФУНКЦИИ ===

// Функция сложения двух чисел
int sum(int a, int b) {
    return a + b;
}

// Функция возведения в степень (циклический вариант)
int power(int base, int exp) {
    int result = 1;
    for (int i = 0; i < exp; i++) {
        result *= base;
    }
    return result;
}

// === РЕКУРСИВНЫЕ ФУНКЦИИ ===

// 1. Факториал: n! = n * (n-1) * ... * 1
int factorial(int n) {
    if (n <= 1) return 1;              // Базовый случай — выход из рекурсии
    return n * factorial(n - 1);       // Рекурсивный вызов
}

// 2. Числа Фибоначчи: 0, 1, 1, 2, 3, 5, 8, ...
int fibonacci(int n) {
    if (n <= 1) return n;              // Базовые случаи: fib(0)=0, fib(1)=1
    return fibonacci(n - 1) + fibonacci(n - 2);
}

// 3. Рекурсивный вывод чисел от n до 1
void countdown(int n) {
    if (n < 1) return;                 // Базовый случай: остановка
    cout << n << " ";
    countdown(n - 1);                  // Рекурсивный вызов
}


// === ГЛАВНАЯ ФУНКЦИЯ ===

int main() {
    cout << "=== ОБЫЧНЫЕ ФУНКЦИИ ===" << endl;
    
    int a = 7, b = 3;
    cout << "sum(" << a << ", " << b << ") = " << sum(a, b) << endl;
    cout << "power(2, 5) = " << power(2, 5) << endl;
    


    cout << "\n=== РЕКУРСИВНЫЕ ФУНКЦИИ ===" << endl;
    
    // Факториал
    int n = 5;
    cout << "factorial(" << n << ") = " << factorial(n) << endl;
    // Пошагово: 5! = 5*4*3*2*1 = 120
    
    // Фибоначчи
    int m = 8;
    cout << "fibonacci(" << m << ") = " << fibonacci(m) << endl;
    // Ряд: 0,1,1,2,3,5,8,13,21 → fib(8) = 21
    
    // Обратный отсчёт
    cout << "countdown(5): ";
    countdown(5);
    cout << endl;
    
    return 0;
}

//Ключевые моменты для рекурсии:

//Базовый случай — условие выхода (например, if (n <= 1) return 1;)
//Рекурсивный шаг — вызов функции с изменёнными параметрами
//Без базового случая — бесконечная рекурсия и ошибка переполнения стека


//Главная идея — коротко
//Функция = блок кода с именем, который можно вызывать.
//Рекурсия = функция вызывает саму себя, пока не дойдёт до условия выхода (иначе бесконечно).