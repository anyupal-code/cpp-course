/*Динамическое программирование - (Dynamic Programming, DP) — это метод решения сложных задач путём разбиения их на более простые подзадачи,
с учётом того, что:
- Подзадачи перекрываются (повторяются).
- Задача обладает оптимальной подструктурой (решение целого можно собрать из решений частей).
- Каждая подзадача решается один раз, а её результат сохраняется (кэшируется), чтобы не вычислять заново.

Проще и короче:
Динамическое программирование — это оптимизация рекурсивного перебора путём сохранения результатов уже решённых подзадач в таблице,
чтобы избежать повторных вычислений.

Важные признаки динамического программирования:
--------------------------------------------------------------------------------------------------
| ПРИЗНАК                  | ЧТО ЭТО ЗНАЧИТ                       | ПРИМЕР (ФИБОНАЧЧИ)           |
--------------------------------------------------------------------------------------------------
| 1. Перекрывающиеся       | Одна подзадача встречается много раз | F(3) — внутри F(5) и F(4)    |
|    подзадачи             |                                      |                              |
--------------------------------------------------------------------------------------------------
| 2. Оптимальная           | Ответ для N через ответы для меньших | F(5) = F(4) + F(3)           |
|    подструктура          |                                      |                              |
--------------------------------------------------------------------------------------------------
| 3. Мемоизация / Таблица  | Сохраняем результат, не пересчитываем| Массив dp[0..N]              |
--------------------------------------------------------------------------------------------------

Отличие от других методов:
--------------------------------------------------------------------------------------------
| МЕТОД                    | ПРИНЦИП                       | КОГДА ИСПОЛЬЗОВАТЬ            |
--------------------------------------------------------------------------------------------
| Разделяй и властвуй      | Делим на непересекающиеся     | Сортировка слиянием,          |
|                          | подзадачи                     | быстрая сортировка            |
--------------------------------------------------------------------------------------------
| Жадные алгоритмы         | Берём локально оптимальное    | Задача о сдаче монет          |
|                          | решение на каждом шаге        | (не всегда работает)          |
--------------------------------------------------------------------------------------------
| Динамическое             | Перебираем все варианты,      | Рюкзак, редакционное          |
| программирование         | но с сохранением              | расстояние, числа Фибоначчи   |
--------------------------------------------------------------------------------------------
*/
#include <iostream>
#include <ctime>
using namespace std;

// ============================================================
// 1. РЕКУРСИЯ (БЕЗ ЗАПОМИНАНИЯ)
// ============================================================
// Сложность: O(2^n) - экспоненциальная
// Почему медленно: каждое число пересчитывается тысячи раз
// Пример: F(5) считает F(3) дважды, F(2) трижды и т.д.
// ============================================================
long long fib_rec(int n) {
    // Базовый случай: F(0) = 0, F(1) = 1
    if (n <= 1) return n;
    
    // Рекурсивный вызов: F(n) = F(n-1) + F(n-2)
    // Без запоминания -> дерево вызовов растёт экспоненциально
    return fib_rec(n - 1) + fib_rec(n - 2);
}

// ============================================================
// 2. ДИНАМИЧЕСКОЕ ПРОГРАММИРОВАНИЕ (Bottom-Up)
// ============================================================
// Сложность: O(n) - линейная
// Почему быстро: каждое число вычисляется ровно 1 раз
// Идём снизу вверх: от F(0) до F(n)
// ============================================================
long long fib_dp(int n) {
    // Базовый случай: F(0) = 0, F(1) = 1
    if (n <= 1) return n;
    
    long long a = 0; // F(0) - предыдущее предыдущее
    long long b = 1; // F(1) - предыдущее
    long long c;     // Текущее F(i)
    
    // Цикл от 2 до n: считаем каждое число один раз
    // Используем только 2 переменные, а не массив (экономия памяти)
    for (int i = 2; i <= n; i++) {
        c = a + b;   // F(i) = F(i-2) + F(i-1)
        a = b;       // Сдвигаем: F(i-2) = F(i-1)
        b = c;       // Сдвигаем: F(i-1) = F(i)
    }
    
    return b; // После цикла b = F(n)
}

// ============================================================
// ГЛАВНАЯ ФУНКЦИЯ
// ============================================================
int main() {
    // Константа: меняйте значение здесь
    // Для рекурсии ставьте n <= 40, иначе будет очень долго
    const int n = 45;
    
    cout << "Вычисление F(" << n << ")" << endl;
    cout << "==============================" << endl;
    
    // ============================================================
    // ЗАМЕР ВРЕМЕНИ ДЛЯ РЕКУРСИИ
    // ============================================================
    cout << "\n--- РЕКУРСИЯ (без запоминания) ---" << endl;
    
    int start = clock();                 // Запоминаем время СТАРТА
    long long result = fib_rec(n);       // Вызываем рекурсивную функцию
    int end = clock();                   // Запоминаем время КОНЦА
    
    double time = (double)(end - start) / CLOCKS_PER_SEC; // Секунды
    
    cout << "F(" << n << ") = " << result << endl;
    cout << "Время: " << time << " секунд" << endl;
    
    // ============================================================
    // ЗАМЕР ВРЕМЕНИ ДЛЯ ДИНАМИЧЕСКОГО ПРОГРАММИРОВАНИЯ
    // ============================================================
    cout << "\n--- ДИНАМИЧЕСКОЕ ПРОГРАММИРОВАНИЕ (с запоминанием) ---" << endl;
    
    start = clock();                     // Запоминаем время СТАРТА
    result = fib_dp(n);                  // Вызываем функцию с ДП
    end = clock();                       // Запоминаем время КОНЦА
    
    time = (double)(end - start) / CLOCKS_PER_SEC; // Секунды
    
    cout << "F(" << n << ") = " << result << endl;
    cout << "Время: " << time << " секунд" << endl;
    
    return 0;
}