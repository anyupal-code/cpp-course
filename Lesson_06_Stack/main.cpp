// Lesson 6: Stack

/*
Стёк - структура (хранения) данных
Стек — это абстрактная структура данных (ADT - Abstract Data Type), которая:
- Организует хранение данных в определенном порядке
- Ограничивает доступ к этим данным (только к вершине)
- Определяет правила добавления и удаления (LIFO)
*/

/*
Главная идея (LIFO)
LIFO = Last In, First Out (последним пришёл — первым вышел).

Представьте стопку тарелок:
- Вы кладёте новую тарелку сверху (push)
- Вы берёте тарелку сверху (pop)
- Вы не можете достать тарелку из середины, не разобрав верхние
*/

/*
+----------+------------------------------------------+------------+
| Операция | Что делает                               | Сложность  |
+----------+------------------------------------------+------------+
| push(x)  | Добавляет элемент x на вершину стека     | O(1)       |
| pop()    | Удаляет элемент с вершины стека          | O(1)       |
| top()    | Возвращает элемент на вершине (не удаляя)| O(1)       |
| empty()  | Проверяет, пуст ли стек                  | O(1)       |
| size()   | Возвращает количество элементов в стеке  | O(1)       |
+----------+------------------------------------------+------------+
*/

#include <iostream>
#include <stack>  // готовый стек из STL

using namespace std;

int main() {
    stack<int> st;  // создаём стек целых чисел
    
    // Добавляем элементы (push)
    st.push(10);
    st.push(20);
    st.push(30);
    
    cout << "Вершина: " << st.top() << endl;  // 30
    cout << "Размер: " << st.size() << endl;   // 3
    
    // Удаляем с вершины (pop)
    st.pop();  // удаляем 30
    
    cout << "Вершина после pop: " << st.top() << endl;  // 20
    
    // Проверка на пустоту
    while (!st.empty()) {
        cout << st.top() << " ";  // выводим 20 10
        st.pop();
    }
    // Вывод: 20 10
    
    return 0;
}