// Lesson 12: Trees in C++

/*
Деревья
1. Теория (Коротко)
A. Что это: Иерархическая структура данных, состоящая из узлов.
Термины:
- Корень (Root): Самый верхний узел (вход в дерево).
- Дети (Children) / Родитель (Parent): Связи между узлами.
- Листья (Leaves): Узлы без детей.

B. Бинарное дерево поиска (BST): Каждый узел имеет не более двух детей (левый и правый).
При этом выполняется правило:
- Все значения в левом поддереве меньше значения текущего узла.
- Все значения в правом поддереве больше значения текущего узла.

2. Как работает (Логика)
Вставка:    Начинаем с корня. Сравниваем новое значение с текущим. Если меньше — идем влево, если больше — вправо.
            Повторяем, пока не найдем пустое место (nullptr).

Поиск:      Аналогично вставке. Двигаемся влево или вправо в зависимости от сравнения.

Удаление:   Сложнее всего. Если у узла нет детей — удаляем. Если один ребенок — заменяем им удаляемый узел.
            Если два ребенка — находим самый левый узел в правом поддереве (минимальный из больших) и заменяем им удаляемый.

3. Зачем нужно
- Быстрый поиск: Гораздо быстрее линейного поиска в списке (O(log n) против O(n)).
- Отсортированные данные: При обходе "в глубину" (симметричном) мы получаем все элементы в отсортированном порядке.
- База данных: Используется для индексов.
- Компиляторы: Используются для построения синтаксических деревьев (AST).

4. Если вставлять элементы строго по порядку (например, 1, 2, 3, 4, 5), дерево выродится в связный список (все узлы будут справа).
Тогда поиск станет таким же медленным, как в списке — O(n).
Для решения этой проблемы используют сбалансированные деревья (AVL или Красно-черные деревья), где высота контролируется автоматически.
В стандартной библиотеке C++ это реализовано в контейнерах std::set и std::map (красно-черное дерево).

4. Использование аглогитма в C++
Контейнер	                                Внутреннее устройство	Поиск	        Вставка	        Сортировка?
std::set / std::map	                        Красно-чёрное дерево	O(log n)	    O(log n)        Да
std::unordered_set / std::unordered_map	    Хеш-таблица	            O(1) в среднем	O(1) в среднем	Нет


*/

// Пример кода (Реализация через указатели)

#include <iostream>
using namespace std;

// ============================================================
// 1. СТРУКТУРА УЗЛА
// ============================================================
struct Node {
    int data;
    Node* left;
    Node* right;
    
    Node(int val) : data(val), left(nullptr), right(nullptr) {}
};

// ============================================================
// 2. КЛАСС БИНАРНОГО ДЕРЕВА ПОИСКА (BST)
// ============================================================
class BinaryTree {
private:
    Node* root;
    
    // --- ВСПОМОГАТЕЛЬНЫЕ РЕКУРСИВНЫЕ ФУНКЦИИ ---
    
    // Вставка
    Node* insertRec(Node* node, int value) {
        if (!node) return new Node(value);
        
        if (value < node->data)
            node->left = insertRec(node->left, value);
        else if (value > node->data)
            node->right = insertRec(node->right, value);
        // если value == node->data — ничего не делаем (уникальность)
        
        return node;
    }
    
    // Поиск
    bool searchRec(Node* node, int value) {
        if (!node) return false;
        if (node->data == value) return true;
        
        if (value < node->data)
            return searchRec(node->left, value);
        else
            return searchRec(node->right, value);
    }
    
    // Обход (для печати)
    void printRec(Node* node) {
        if (!node) return;
        printRec(node->left);
        cout << node->data << " ";
        printRec(node->right);
    }
    
    // Очистка памяти
    void clearRec(Node* node) {
        if (!node) return;
        clearRec(node->left);
        clearRec(node->right);
        delete node;
    }
    
public:
    // --- ПУБЛИЧНЫЙ ИНТЕРФЕЙС ---
    
    BinaryTree() : root(nullptr) {}
    
    ~BinaryTree() {
        clearRec(root);
    }
    
    void insert(int value) {
        root = insertRec(root, value);
    }
    
    bool search(int value) {
        return searchRec(root, value);
    }
    
    void print() {
        printRec(root);
        cout << endl;
    }
};

// ============================================================
// 3. ДЕМОНСТРАЦИЯ РАБОТЫ
// ============================================================
int main() {
    cout << "=== БИНАРНОЕ ДЕРЕВО ПОИСКА ===\n\n";
    
    BinaryTree tree;
    
    // Вставляем элементы
    cout << "Вставляем: 10, 5, 15, 3, 7, 20\n";
    tree.insert(10);
    tree.insert(5);
    tree.insert(15);
    tree.insert(3);
    tree.insert(7);
    tree.insert(20);
    
    // Выводим дерево (отсортированный порядок)
    cout << "Дерево (sorted): ";
    tree.print();  // 3 5 7 10 15 20
    
    // Поиск
    cout << "\nПоиск 7: " << (tree.search(7) ? "НАЙДЕН" : "НЕ НАЙДЕН") << endl;
    cout << "Поиск 99: " << (tree.search(99) ? "НАЙДЕН" : "НЕ НАЙДЕН") << endl;
    
    // ============================================================
    // 4. ДЕМОНСТРАЦИЯ ПРОБЛЕМЫ ВЫРОЖДЕНИЯ
    // ============================================================
    cout << "\n=== ПРОБЛЕМА ВЫРОЖДЕНИЯ ===\n";
    cout << "Вставляем числа по порядку: 1, 2, 3, 4, 5\n";
    
    BinaryTree badTree;
    badTree.insert(1);
    badTree.insert(2);
    badTree.insert(3);
    badTree.insert(4);
    badTree.insert(5);
    
    cout << "Дерево выродилось в список: ";
    badTree.print();  // 1 2 3 4 5 (но структура — это лестница!)
    
    cout << "\n!!! Поиск теперь работает за O(n), а не O(log n) !!!\n";
    cout << "Решение — сбалансированные деревья (урок 13)\n";
    
    return 0;
}
