// Lesson 7: Sequences


/*
Последовательные контейнеры (sequence containers) в C++.
Главная их особенность (в отличие от ассоциативных контейнеров вроде std::map или std::set)
— элементы упорядочены строго в том порядке, в котором вы их добавили. У каждого элемента есть свой индекс или позиция.

4 основных типа: std::array, std::vector, std::deque, std::list.

============================================================
1. std::array - статический массив фиксированного размера
============================================================
Принцип работы:
- Это надстройка над обычным C-массивом int arr[10].
- Размер известен на этапе компиляции.
- Память выделяется на стеке (или статически).

Когда использовать:
- Когда количество элементов известно заранее и не меняется (например, дни недели, математические матрицы 3x3).

============================================================
2. std::vector - динамический массив (самый популярный)
============================================================
Принцип работы:
- Хранит элементы в непрерывном блоке памяти (как массив).
- Когда места не хватает, вектор автоматически выделяет новый больший кусок памяти, копирует/перемещает туда старые элементы и удаляет старый блок.

Важнейший нюанс:
- Доступ по индексу [i] — мгновенный (O(1)).
- Добавление в конец (push_back) — в среднем мгновенное (O(1)), но иногда происходит дорогое перевыделение памяти.
- Вставка/удаление в середину или начало — очень медленная (O(n)), так как все элементы сдвигаются.

Когда использовать:
В 80% случаев. Когда вам нужен быстрый доступ по индексу и вы добавляете элементы преимущественно в конец.

============================================================
3. std::deque - дек (двусторонняя очередь)
============================================================
Принцип работы:
- Это "вектор с двумя концами".
- Внутри это массив указателей на блоки памяти фиксированного размера.

Главное отличие от vector:
- Добавление/удаление в начало (push_front / pop_front) происходит так же быстро (O(1)), как и в конец.
- Доступ по индексу [i] — тоже быстрый (O(1)), но чуть медленнее, чем у vector, так как нужно вычислить, в каком блоке лежит индекс.
- Вставка в середину — всё ещё медленная (O(n)).

Когда использовать:
Когда вам нужна очередь (FIFO), либо когда вы активно добавляете элементы и в начало, и в конец.

============================================================
4. std::list - двусвязный список
============================================================
Принцип работы:
- Каждый элемент хранится в отдельном узле памяти, который содержит указатели на предыдущий и следующий узлы.
- Элементы не лежат рядом в памяти.

Главные особенности:
- Нет оператора [i] (доступа по индексу). Чтобы найти элемент по номеру, нужно пройти по списку от начала — это медленно (O(n)).
- Зато вставка и удаление в любом месте (если у вас уже есть итератор на это место) происходит мгновенно (O(1)) — просто перекидываются указатели.
- Элементы никогда не "перевыделяются" и не сдвигаются, поэтому итераторы никогда не инвалидируются (кроме как для удаленного элемента).

Когда использовать:
- Когда вы постоянно вставляете/удаляете элементы в середине огромного контейнера, а доступ по индексу вам не нужен.

================================================="
Сводная таблица сложности операций:" << endl;
-----------------------------------------------
Операция           | array | vector | deque | list
-----------------------------------------------
Доступ по индексу  | O(1)  | O(1)   | O(1)  | Нет
Вставка в конец    | Нет   | O(1)*  | O(1)  | O(1)
Вставка в начало   | Нет   | O(n)   | O(1)  | O(1)
Вставка в середину | Нет   | O(n)   | O(n)  | O(1)**
-----------------------------------------------
* - амортизированная константа" << endl;
** - при наличии итератора" << endl;
=================================================

*/



#include <iostream>
#include <array>
#include <vector>
#include <deque>
#include <list>

using namespace std;

// ============================================================
// 1. std::array - статический массив фиксированного размера
// ============================================================
void demo_array() {
    cout << "\n========== std::array ==========" << endl;
    
    // Создание массива из 5 целых чисел
    array<int, 5> arr = {10, 20, 30, 40, 50};
    
    // Доступ по индексу (без проверки границ)
    cout << "arr[0] = " << arr[0] << endl; // 10
    
    // Доступ с проверкой границ (бросит исключение при ошибке)
    cout << "arr.at(4) = " << arr.at(4) << endl; // 50
    
    // Размер известен на этапе компиляции
    cout << "Размер: " << arr.size() << endl; // 5
    
    // Перебор элементов (for-each)
    cout << "Элементы: ";
    for (int val : arr) {
        cout << val << " ";
    }
    cout << endl;
    
    // Изменение элемента
    arr[2] = 999;
    cout << "После изменения arr[2] = 999: ";
    for (int val : arr) {
        cout << val << " ";
    }
    cout << endl;
}

// ============================================================
// 2. std::vector - динамический массив (самый популярный)
// ============================================================
void demo_vector() {
    cout << "\n========== std::vector ==========" << endl;
    
    vector<int> v;
    
    // Добавление элементов в конец
    v.push_back(1);
    v.push_back(2);
    v.push_back(3);
    
    cout << "Размер: " << v.size() << endl;          // 3
    cout << "Вместимость: " << v.capacity() << endl; // Обычно 4 (выделяют с запасом)
    
    // Доступ по индексу (быстрый O(1))
    v[1] = 99;
    cout << "После v[1] = 99: ";
    for (int x : v) {
        cout << x << " "; // 1 99 3
    }
    cout << endl;
    
    // Удаление последнего элемента
    v.pop_back(); // теперь {1, 99}
    cout << "После pop_back(): ";
    for (int x : v) {
        cout << x << " ";
    }
    cout << endl;
    
    // Вставка в середину (ДОРОГО! O(n))
    v.insert(v.begin() + 1, 777); // вставляем 777 на позицию 1
    cout << "После вставки 777 на позицию 1: ";
    for (int x : v) {
        cout << x << " "; // 1 777 99
    }
    cout << endl;
    
    // Заранее резервируем память, чтобы избежать лишних перевыделений
    vector<int> big;
    big.reserve(1000); // Сразу выделяем место под 1000 элементов
    cout << "Вместимость после reserve(1000): " << big.capacity() << endl;
    
    // Удаление по итератору
    v.erase(v.begin()); // удаляем первый элемент
    cout << "После удаления первого элемента: ";
    for (int x : v) {
        cout << x << " "; // 777 99
    }
    cout << endl;
}

// ============================================================
// 3. std::deque - дек (двусторонняя очередь)
// ============================================================
void demo_deque() {
    cout << "\n========== std::deque ==========" << endl;
    
    deque<int> d;
    
    // Добавление в оба конца (оба O(1))
    d.push_back(10);   // {10}
    d.push_front(20);  // {20, 10}
    d.push_back(30);   // {20, 10, 30}
    d.push_front(40);  // {40, 20, 10, 30}
    
    cout << "Элементы: ";
    for (int x : d) {
        cout << x << " "; // 40 20 10 30
    }
    cout << endl;
    
    // Доступ по индексу (O(1), но чуть медленнее вектора)
    cout << "Первый: " << d[0] << endl;   // 40
    cout << "Последний: " << d[3] << endl; // 30
    
    // Удаление с обоих концов
    d.pop_front(); // {20, 10, 30}
    cout << "После pop_front(): ";
    for (int x : d) {
        cout << x << " ";
    }
    cout << endl;
    
    d.pop_back();  // {20, 10}
    cout << "После pop_back(): ";
    for (int x : d) {
        cout << x << " ";
    }
    cout << endl;
    
    // Вставка в середину (медленно, O(n))
    d.insert(d.begin() + 1, 555); // {20, 555, 10}
    cout << "После вставки 555 в середину: ";
    for (int x : d) {
        cout << x << " ";
    }
    cout << endl;
    
    // Размер
    cout << "Размер: " << d.size() << endl;
}

// ============================================================
// 4. std::list - двусвязный список
// ============================================================
void demo_list() {
    cout << "\n========== std::list ==========" << endl;
    
    list<int> lst = {1, 2, 3, 4, 5};
    
    // Добавление в начало и конец (O(1))
    lst.push_front(0); // {0, 1, 2, 3, 4, 5}
    lst.push_back(6);  // {0, 1, 2, 3, 4, 5, 6}
    
    cout << "Начальный список: ";
    for (int x : lst) {
        cout << x << " ";
    }
    cout << endl;
    
    // Вставка в середину (БЫСТРО! O(1), если есть итератор)
    auto it = lst.begin(); // указывает на 0
    ++it; // теперь указывает на 1
    ++it; // теперь указывает на 2
    lst.insert(it, 999); // Вставляем 999 перед 2
    cout << "После вставки 999 перед 2: ";
    for (int x : lst) {
        cout << x << " "; // 0 1 999 2 3 4 5 6
    }
    cout << endl;
    
    // Удаление по значению (медленно, O(n))
    lst.remove(3);
    cout << "После remove(3): ";
    for (int x : lst) {
        cout << x << " "; // 0 1 999 2 4 5 6
    }
    cout << endl;
    
    // Удаление по итератору (БЫСТРО! O(1))
    auto it_to_erase = lst.begin();
    ++it_to_erase; // указывает на 1
    lst.erase(it_to_erase); // удаляем 1
    cout << "После удаления второго элемента: ";
    for (int x : lst) {
        cout << x << " "; // 0 999 2 4 5 6
    }
    cout << endl;
    
    // Доступ по индексу ОТСУТСТВУЕТ!
    // cout << lst[2]; // ОШИБКА КОМПИЛЯЦИИ!
    
    // Получение первого и последнего элемента
    cout << "Первый элемент: " << lst.front() << endl; // 0
    cout << "Последний элемент: " << lst.back() << endl; // 6
    
    // Размер
    cout << "Размер: " << lst.size() << endl;
}

