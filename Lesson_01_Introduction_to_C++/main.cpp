// Lesson 01: Introduction to C++

/* ВВедение в С++
C++ — это мощный компилируемый язык программирования общего назначения.
Исторически — надстройка (C with Classes) к C
Весь код на C являлся корректным кодом на C++ (за редкими исключениями).
C++ — это C + ООП + шаблоны + перегрузка.
*/

/*Конкретнее:
«C» + «Классы» — исторически это расширение языка Си, в которое добавили объектно-ориентированное программирование (классы, наследование, полиморфизм).

Скорость C + Удобство высокоуровневых языков — дает полный контроль над памятью и железом (как в C), но при этом позволяет писать сложный код проще и безопаснее (благодаря шаблонам, STL и ООП).

Мультипарадигменный — на нем можно писать в процедурном стиле (как на C), в объектно-ориентированном, в функциональном и даже в метапрограммном стиле (шаблоны).

Где используется:
Игры, движки (Unreal), операционные системы, браузеры (Chrome), высоконагруженные серверы, робототехника, финансы — везде, где критична производительность.
*/


//Основа, на чем строится язык:

//1. Отличие от C
//C++ — это объектно-ориентированное расширение C. Главное отличие: классы и работа с памятью через ссылки (&), а не только через указатели (*).

//2. Базовый каркас программы:

#include <iostream> // Ввод-вывод

int main() {
    std::cout << "Hello World!"; // Вывод
    return 0;
}

//3. Пространства имен (namespace)
//Чтобы не было конфликтов имен. Стандартная библиотека лежит в std.
using namespace std; // Тогда можно писать cout вместо std::cout

//4. Ввод и вывод (вместо printf/scanf):

int x;
cin >> x;          // Ввод
cout << "x = " << x; // Вывод


//5. Классы и ООП (главное новшество):

class Cat {
public:          // Доступно всем
    string name;
    void meow() { cout << name << " says meow"; }
private:         // Доступно только внутри класса
    int age;
};

//6. Конструкторы и Деструкторы:

class Cat {
public:
    Cat() { /* Создание объекта */ }  // Конструктор
    ~Cat() { /* Очистка ресурсов */ } // Деструктор
};

//7. new и delete (вместо malloc/free)
//Выделение памяти в куче (динамически):

int* p = new int(5);   // Выделение
delete p;              // Освобождение (обязательно!)

//8. Ссылки (&) — безопаснее указателей:

int a = 10;
int &ref = a;  // ref — это псевдоним a
ref = 20;      // Теперь a = 20

//9. Перегрузка функций и операторов
//Можно создавать несколько функций с одним именем, но разными аргументами:

int sum(int a, int b) { return a + b; }
double sum(double a, double b) { return a + b; }

//10. Шаблоны (Templates) — код под любой тип

template <typename T>
T max(T a, T b) { return (a > b) ? a : b; }

//11. STL (Стандартная библиотека шаблонов)
/*Вместо самописных массивов и списков используйте готовые контейнеры:
- vector — динамический массив (заменяет []).
- string — текст (заменяет char*).
- map — словарь (ключ → значение).*/

#include <vector>
vector<int> nums = {1, 2, 3};
nums.push_back(4); // Добавили 4

/*
Три «золотых» правила новичка в C++:
- RAII — ресурс выделяется в конструкторе, освобождается в деструкторе (чтобы не забывать delete).
- Умные указатели (unique_ptr, shared_ptr) вместо голых new/delete (современный C++).
- const везде, где можно — защищает от случайных изменений.*/