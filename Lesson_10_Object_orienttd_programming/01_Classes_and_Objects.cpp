/*
1. Классы и Объекты

Класс — это чертеж (шаблон) объекта.
Объект — это конкретный экземпляр класса (реализация чертежа).


A. Класс — это чертёж (шаблон)
Смысл:  Класс описывает структуру и поведение — какие данные будут у объекта и что он сможет делать.
Зачем:  Чтобы не писать один и тот же код для каждого нового экземпляра.
    Чтобы описать тип данных, которого нет в языке (например, Student, BankAccount, Car).
    Чтобы сгруппировать связанные данные и функции в одном месте.

B. Объект — это конкретный экземпляр класса
Смысл:      Объект — это реализация чертежа в памяти компьютера. У него есть конкретные значения полей.
Зачем:      Чтобы хранить реальные данные (например, конкретного студента — имя "Иван", возраст 20).
            Чтобы использовать класс на практике (чертеж сам по себе ничего не делает, нужен дом).
*/

#include <iostream>
#include <string>

// 1. Объявление класса (чертеж)
class Car {
public:
    std::string model;
    int year;

    // Метод класса (функция)
    void info() {
        std::cout << model << ", " << year << std::endl;
    }
};

int main() {
    // 2. Создание объекта (экземпляр)
    Car myCar;
    myCar.model = "Tesla";
    myCar.year = 2023;
    myCar.info(); // Вывод: Tesla, 2023
    return 0;
}