/*
3. Наследование
Смысл:  Создание нового класса (производного) на основе уже существующего (базового).
        Производный класс перенимает методы и поля родителя и может их расширять.
Зачем:  Переиспользование кода и создание иерархий (например, Собака — это частный случай Животное).
*/

#include <iostream>

// Базовый класс (Родитель)
class Animal {
public:
    std::string name;
    void eat() {
        std::cout << name << " кушает.\n";
    }
};

// Производный класс (Наследник)
class Dog : public Animal {
public:
    void bark() { // Новый метод, которого нет у Animal
        std::cout << name << " гавкает: Гав!\n";
    }
};

int main() {
    Dog myDog;
    myDog.name = "Рекс"; // Поле унаследовано от Animal
    myDog.eat();         // Метод унаследован
    myDog.bark();        // Собственный метод
    return 0;
}