// Объектно-ориентированное програамирование

/*
Объектно-ориентированное программирование (ООП) в C++ — это способ организации кода, где данные и функции объединяются в объекты.
Это позволяет моделировать реальные сущности и управлять сложностью программ.
*/

/*
============================================================
ОСНОВЫ ООП В C++ (КРАТКИЙ КОНСПЕКТ)
============================================================

| ПОНЯТИЕ       | КРАТКО                            | В КОДЕ (ПРИМЕР) |
|-----------------------------------------------------------|
| Класс         | Тип данных (чертеж)               | class Car {}; |
| Объект        | Экземпляр класса                  | Car myCar; |
| Инкапсуляция  | Скрытие данных                    | private: + публичные getBalance() |
| Наследование  | Расширение функционала            | class Dog : public Animal |
| Полиморфизм   | Один интерфейс - разная реализ.   | virtual void area() + override |

============================================================
ДОПОЛНИТЕЛЬНО:
- Конструктор: Car() { ... }
- Деструктор: ~Car() { ... }
- this: указатель на текущий объект
============================================================
*/

