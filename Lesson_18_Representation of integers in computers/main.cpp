/*
Представление целых чисел в компьютерах (Representation of integers in computers)

Компьютер оперирует только нулями и единицами (битами). Целые числа хранятся в двоичной системе.
Разрядность — это количество бит, отведенных под одно число (например, 8 бит = 1 байт).
Чем больше разрядность, тем шире диапазон чисел, которые можно записать.

2. Беззнаковые (unsigned)
Суть: Числа только положительные (от 0 и выше). Все биты отведены под само число.
Диапазон: от 0 до 2^n - 1 (где n — количество бит).

Пример (8 бит):
Минимум: 0000 0000 = 0
Максимум: 1111 1111 = 255

3. Знаковые (int) через дополнительный код
Суть: Числа отрицательные и положительные. Старший (левый) бит отводится под знак:
0 — число положительное.
1 — число отрицательное.

Почему "дополнительный код"?
Чтобы не делать два разных алгоритма для сложения и вычитания, отрицательные числа хранятся так, чтобы их можно было складывать с положительными "как есть" (по правилам двоичного сложения).

Правило перевода в дополнительный код (для отрицательного числа):
Берем модуль числа (положительное).
Инвертируем все биты (меняем 0 на 1, 1 на 0) — это обратный код.
Прибавляем 1 (это и есть дополнительный код).
Диапазон: от -2^(n-1) до 2^(n-1) - 1
Пример (8 бит, диапазон от -128 до 127):

+5 - 0000 0101
Берем +5 (0000 0101)
Инвертируем: 1111 1010
Прибавляем 1: 1111 1011
-5 - 1111 1011

Шпаргалка по диапазонам (Таблица)
Тип	Разрядность	Беззнаковый (unsigned)	Знаковый (signed)
char	8 бит	0 ... 255	-128 ... 127
short	16 бит	0 ... 65,535	-32,768 ... 32,767
int	32 бита	0 ... 4,294,967,295	-2,147,483,648 ... 2,147,483,647
long long	64 бита	0 ... 1.8e19	-9.2e18 ... 9.2e18
Итог (запомнить):
unsigned — только плюс, больше диапазон в положительную сторону.

signed (int) — плюс и минус, старший бит — знак.

Дополнительный код нужен, чтобы -5 выглядело как ...1011 и при сложении 5 + (-5) давало ровно 0 без лишних действий процессора.

Осторожнее с переполнением! В int максимум + 1 дает отрицательное число, а в unsigned максимум + 1 дает 0.
*/

// Самый простой способ увидеть разницу — переполнить переменную.

#include <iostream>
#include <iomanip> // для вывода hex

int main() {
    // --- 1. БЕЗЗНАКОВЫЙ (unsigned) ---
    // 8 бит (диапазон 0...255)
    unsigned char a = 255; 
    std::cout << "unsigned a = " << (int)a << std::endl; // 255

    a = a + 1; // ПЕРЕПОЛНЕНИЕ!
    std::cout << "a + 1 = " << (int)a << std::endl; // 0 (циклический сброс)
    
    // --- 2. ЗНАКОВЫЙ (signed int) ---
    // 32 бита (диапазон -2,147,483,648 ... 2,147,483,647)
    int b = 2147483647; // Максимум для 32-битного int
    std::cout << "int b = " << b << std::endl;

    b = b + 1; // ПЕРЕПОЛНЕНИЕ!
    std::cout << "b + 1 = " << b << std::endl; 
    // Выведет: -2147483648 (из-за дополнительного кода число перескочило в минус)

    // --- 3. Смотрим, как выглядят биты (HEX) ---
    int positive = 5;
    int negative = -5;
    
    std::cout << "5 в HEX: 0x" << std::hex << positive << std::endl; // 0x5
    std::cout << "-5 в HEX: 0x" << std::hex << negative << std::endl; 
    // Выведет: 0xFFFFFFFB (это и есть дополнительный код для -5 в 32 битах)
    
    return 0;
}


