// Lesson 10. Sorting

/*
В C++ подход к сортировке кардинально отличается от языка C или чистого алгоритмического программирования.
Здесь есть стандартная библиотека (STL), которая решает 95% задач.
std::sort
Это не просто «быстрая сортировка».
Это гибридный алгоритм (обычно Introsort — смесь быстрой сортировки, пирамидальной и сортировки вставками).
*/

/*
Алгоритмы сортировки (теория)
Алгоритм         | Средняя   | Худшая    | Память   | Стабильн.| Суть
-----------------|-----------|-----------|----------|----------|-----------------------------------------
Пузырек          | O(N^2)    | O(N^2)    | O(1)     | Да       | Соседние элементы меняются местами
Вставками        | O(N^2)    | O(N^2)    | O(1)     | Да       | Вставка элемента в отсортированную часть
Слиянием         | O(N log N)| O(N log N)| O(N)     | Да       | Разделение и слияние половин
Быстрая          | O(N log N)| O(N^2)    | O(log N) | Нет      | Разбиение по опорному элементу
Пирамидальная    | O(N log N)| O(N log N)| O(1)     | Нет      | Построение кучи и извлечение корня
*/

/* Сортировка в C++
Функция             | Что делает                       | Когда использовать
--------------------+----------------------------------+------------------------------------------
std::sort           | Сортирует всё                    | Всегда по умолчанию
std::partial_sort   | Сортирует только первые N        | Нужны только лучшие/худшие N элементов
std::is_sorted      | Проверяет, отсортировано ли      | Перед сортировкой, чтобы не делать лишней работы
std::is_sorted_until| Находит место нарушения          | Чтобы узнать, где порядок сломался
std::nth_element    | Ставит элемент на нужную позицию | Нужна медиана или элемент по порядку
std::stable_sort    | Стабильная сортировка            | Важен порядок равных элементов
*/

/*
Когда что использовать:
std::partial_sort — когда нужно найти первые N наименьших/наибольших элементов (например, топ-10 игроков).
std::is_sorted — для оптимизации: если массив уже отсортирован, можно пропустить сортировку (актуально для больших данных).
std::nth_element — когда нужно найти медиану или квантиль (быстрее, чем полная сортировка).
std::stable_sort — когда важен порядок равных элементов (например, сортировка по нескольким полям).
*/

#include <algorithm>
#include <vector>
#include <iostream>

int main() {
    std::vector<int> data = {5, 2, 8, 1, 9, 3, 7, 4, 6};
    
    // ==========================================
    // 1. Обычная сортировка
    // ==========================================
    
    // По возрастанию
    std::sort(data.begin(), data.end());
    // Результат: {1, 2, 3, 4, 5, 6, 7, 8, 9}
    
    // По убыванию
    std::sort(data.begin(), data.end(), std::greater<int>());
    // Результат: {9, 8, 7, 6, 5, 4, 3, 2, 1}
    
    // Своя логика (лямбда)
    std::sort(data.begin(), data.end(), [](int a, int b) {
        return a > b; // тоже убывание
    });
    
    // ==========================================
    // 2. Частичная сортировка (std::partial_sort)
    // ==========================================
    
    std::vector<int> nums = {9, 1, 8, 2, 7, 3, 6, 4, 5};
    
    // Отсортировать только первые 3 элемента (будут самые маленькие)
    std::partial_sort(nums.begin(), nums.begin() + 3, nums.end());
    // Результат: {1, 2, 3, 9, 8, 7, 6, 5, 4}
    //           ^^^^^^^^
    //           отсортированы первые 3
    
    // Найти 3 наибольших элемента
    std::vector<int> scores = {78, 92, 45, 88, 99, 61};
    std::partial_sort(scores.begin(), scores.begin() + 3, 
                      scores.end(), std::greater<int>());
    // Результат: {99, 92, 88, 45, 78, 61}
    //            ^^^^^^^^^^
    //            три лучших результата
    
    // ==========================================
    // 3. Проверка упорядоченности (std::is_sorted)
    // ==========================================
    
    std::vector<int> sorted = {1, 2, 3, 4, 5};
    std::vector<int> unsorted = {5, 2, 8, 1, 9};
    
    // Проверка по возрастанию
    if (std::is_sorted(sorted.begin(), sorted.end())) {
        std::cout << "Вектор отсортирован по возрастанию\n";
    }
    
    // Проверка по убыванию
    if (std::is_sorted(sorted.begin(), sorted.end(), std::greater<int>())) {
        std::cout << "Вектор отсортирован по убыванию\n";
    } else {
        std::cout << "Вектор НЕ отсортирован по убыванию\n";
    }
    
    // Проверка перед сортировкой (чтобы не делать лишнюю работу)
    if (!std::is_sorted(unsorted.begin(), unsorted.end())) {
        std::sort(unsorted.begin(), unsorted.end());
        // Сортируем только если это нужно
    }
    
    // ==========================================
    // 4. Где нарушился порядок (std::is_sorted_until)
    // ==========================================
    
    std::vector<int> almost = {1, 2, 3, 5, 4, 6, 7};
    auto it = std::is_sorted_until(almost.begin(), almost.end());
    // it указывает на элемент 4 (индекс 4), потому что 5 > 4
    
    int pos = it - almost.begin(); // pos == 4
    std::cout << "Порядок нарушен на позиции: " << pos << "\n";
    
    // ==========================================
    // 5. nth_element - найти элемент на позиции
    // ==========================================
    
    std::vector<int> values = {9, 1, 8, 2, 7, 3, 6, 4, 5};
    
    // Найти медиану (элемент на позиции 4)
    std::nth_element(values.begin(), values.begin() + 4, values.end());
    // Теперь values[4] == 5 (медиана)
    // Слева все элементы <= 5, справа все >= 5
    std::cout << "Медиана: " << values[4] << "\n";
    
    // ==========================================
    // 6. Стабильная сортировка (std::stable_sort) - с сохранением порядка равных
    // ==========================================
    
    struct Person {
        std::string name;
        int age;
    };
    
    std::vector<Person> people = {
        {"Alice", 30},
        {"Bob", 25},
        {"Charlie", 30},
        {"David", 25}
    };
    
    // Сортировка по возрасту с сохранением порядка равных
    std::stable_sort(people.begin(), people.end(), 
                     [](const Person& a, const Person& b) {
                         return a.age < b.age;
                     });
    // Вывод на экран после сортировки
    std::cout << "Отсортированный список:\n";
    for (const auto& person : people) {
        std::cout << person.name << " - " << person.age << " лет\n";
    }

    std::cout << "Отсортированный список в одну строку: ";
    for (const auto& p : people) {
        std::cout << p.name << "(" << p.age << ") ";
    }
    std::cout << "\n"; 

    // Результат: Bob(25), David(25), Alice(30), Charlie(30)
    // Обратите внимание: Bob был до David, Alice до Charlie
    // Порядок среди 25-летних и 30-летних сохранился
    
    return 0;
}